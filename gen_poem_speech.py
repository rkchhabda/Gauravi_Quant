import asyncio, edge_tts

TEXT = """धुएँ वाले इंजन से चली थी कहानी,
भाप की ताकत से दौड़ी रेल पुरानी।
समय बदला, बदली हर तस्वीर नई,
बिजली के इंजन से रफ़्तार बढ़ी।

लोहे की पटरी पर सपने हैं दौड़ते,
हर स्टेशन पर हज़ारों कदम हैं जुड़ते।
यह रेल नहीं, यह देश की है शान,
इसकी सफ़ाई है हम सबका सम्मान।

मत फेंको कचरा, मत करो गंदगी,
स्वच्छ रहे डिब्बा, स्वच्छ रहे हर सीढ़ी।
यह ज़िम्मेदारी है हर नागरिक की,
सामाजिक फ़र्ज़ है, न भूलो कभी।

जैसे हम रखते हैं घर को साफ़-सुथरा,
वैसे ही चमके यह रेल का हर चेहरा।
आओ मिलकर लें आज यह प्रण,
स्वच्छ रेलवे, स्वच्छ हो हर जन-मन।

स्वच्छ रेल, स्वस्थ देश!"""

async def main():
    c = edge_tts.Communicate(TEXT, voice="hi-IN-SwaraNeural", rate="-8%", pitch="+2Hz")
    await c.save("poem_voice.mp3")

asyncio.run(main())
print("voice done")
